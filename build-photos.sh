#!/bin/bash
# Regenerate web-optimized gallery images + manifest from the source photo library.
# Edit the SRC path or the PHOTOS list below to add/remove images, then re-run:
#   bash build-photos.sh
set -e

# Source folders searched (in order) for each photo's base filename.
